-- -------------------------------------------
-- Table: players
-- -------------------------------------------
DROP TABLE IF EXISTS `players`;
CREATE TABLE `players` (
                           `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
                           `uuid` VARCHAR(36) NOT NULL,
                           `first_nick` VARCHAR(16) NOT NULL,
                           `last_nick` VARCHAR(16) NOT NULL,
                           `first_ip` VARCHAR(45),
                           `last_ip` VARCHAR(45),
                           `last_country` VARCHAR(100),
                           `last_country_code` VARCHAR(5),
                           `is_online` TINYINT(1) DEFAULT 0,
                           `is_whitelisted` TINYINT(1) DEFAULT 0,
                           `is_blacklisted` TINYINT(1) DEFAULT 0,
                           `total_connections` INT UNSIGNED DEFAULT 1,
                           `first_seen` TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                           `last_seen` TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
                           PRIMARY KEY (`id`),
                           UNIQUE KEY `uk_uuid` (`uuid`),
                           KEY `idx_last_nick` (`last_nick`),
                           KEY `idx_is_online` (`is_online`),
                           KEY `idx_last_seen` (`last_seen`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- -------------------------------------------
-- Table: player_nicks
-- -------------------------------------------
DROP TABLE IF EXISTS `player_nicks`;
CREATE TABLE `player_nicks` (
                                `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
                                `player_id` INT UNSIGNED NOT NULL,
                                `nick` VARCHAR(16) NOT NULL,
                                `first_used` TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                                `last_used` TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
                                PRIMARY KEY (`id`),
                                UNIQUE KEY `uk_player_nick` (`player_id`, `nick`),
                                KEY `idx_nick` (`nick`),
                                CONSTRAINT `fk_nick_player` FOREIGN KEY (`player_id`) REFERENCES `players` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- -------------------------------------------
-- Table: player_ips
-- -------------------------------------------
DROP TABLE IF EXISTS `player_ips`;
CREATE TABLE `player_ips` (
                              `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
                              `player_id` INT UNSIGNED NOT NULL,
                              `ip` VARCHAR(45) NOT NULL,
                              `country` VARCHAR(100),
                              `country_code` VARCHAR(5),
                              `isp` VARCHAR(255),
                              `asn` VARCHAR(50),
                              `first_used` TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                              `last_used` TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
                              PRIMARY KEY (`id`),
                              UNIQUE KEY `uk_player_ip` (`player_id`, `ip`),
                              KEY `idx_ip` (`ip`),
                              CONSTRAINT `fk_ip_player` FOREIGN KEY (`player_id`) REFERENCES `players` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- -------------------------------------------
-- Table: player_connections
-- -------------------------------------------
DROP TABLE IF EXISTS `player_connections`;
CREATE TABLE `player_connections` (
                                      `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
                                      `uuid` VARCHAR(36) NOT NULL,
                                      `nick` VARCHAR(16) NOT NULL,
                                      `ip` VARCHAR(45) NOT NULL,
                                      `ip_version` ENUM('ipv4', 'ipv6') DEFAULT 'ipv4',
                                      `country` VARCHAR(100),
                                      `country_code` VARCHAR(5),
                                      `region` VARCHAR(100),
                                      `city` VARCHAR(100),
                                      `isp` VARCHAR(255),
                                      `org` VARCHAR(255),
                                      `asn` VARCHAR(50),
                                      `asname` VARCHAR(255),
                                      `is_proxy` TINYINT(1) DEFAULT 0,
                                      `is_vpn` TINYINT(1) DEFAULT 0,
                                      `is_hosting` TINYINT(1) DEFAULT 0,
                                      `is_mobile` TINYINT(1) DEFAULT 0,
                                      `latitude` DECIMAL(10, 8),
                                      `longitude` DECIMAL(11, 8),
                                      `timezone` VARCHAR(50),
                                      `game_version` VARCHAR(20),
                                      `blocked` TINYINT(1) DEFAULT 0,
                                      `block_reason` VARCHAR(100),
                                      `raw_data` JSON,
                                      `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                                      PRIMARY KEY (`id`),
                                      KEY `idx_uuid` (`uuid`),
                                      KEY `idx_nick` (`nick`),
                                      KEY `idx_ip` (`ip`),
                                      KEY `idx_blocked` (`blocked`),
                                      KEY `idx_created_at` (`created_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

